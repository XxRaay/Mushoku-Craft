    /**
     * Resolves the deterministic, collision-free pattern index for a given circle type in a given world seed.
     * Uses a seeded Fisher-Yates permutation of the entire pattern pool:
     * - Each registered circle type receives a unique pattern index in that seed.
     * - The same pattern can map to Teleportation in one seed, Summoning in another seed, or a dud in a third seed.
     * - Excess patterns in the pool act as inactive ancient duds (do nothing).
     */
    public static int getPatternIndexForSeed(long seed, ResourceLocation circleTypeId) {
        if (circleTypeId == null || ALL_PATTERNS.isEmpty()) return -1;
        List<ResourceLocation> allTypes = MagicCircleRegistry.getAllIdsSorted();
        int typeIndex = allTypes.indexOf(circleTypeId);
        if (typeIndex < 0 || typeIndex >= ALL_PATTERNS.size()) {
            return -1;
        }

        int[] shuffled = new int[ALL_PATTERNS.size()];
        for (int i = 0; i < shuffled.length; i++) {
            shuffled[i] = i;
        }
        Random random = new Random(seed);
        for (int i = shuffled.length - 1; i > 0; i--) {
            int j = random.nextInt(i + 1);
            int temp = shuffled[i];
            shuffled[i] = shuffled[j];
            shuffled[j] = temp;
        }

        return shuffled[typeIndex];
    }

    public static MagicCirclePattern getPatternForSeed(long seed, ResourceLocation circleTypeId) {
        int idx = getPatternIndexForSeed(seed, circleTypeId);
        if (idx >= 0 && idx < ALL_PATTERNS.size()) {
            return ALL_PATTERNS.get(idx);
        }
        return null;
    }

    public static int getTeleportPatternIndexForSeed(long seed) {
        return getPatternIndexForSeed(seed, TeleportCircleType.ID);
    }

    public static MagicCirclePattern getTeleportPatternForSeed(long seed) {
        return getPatternForSeed(seed, TeleportCircleType.ID);
    }
